async def test_num(dut: HierarchyObject, num_img, expected_val: int):
    await init(dut)
    dut.data_in_0.value = sw2hw(num_img)
    await RisingEdge(dut.clk)
    await ClockCycles(dut.clk, 1)

    res = [int(str(_), 2) for _ in dut.data_out_0.value]
    res_max = max(res)
    res_ind = res.index(res_max)

    # read output signal
    print(f"=============================")
    print(f"test_num_{expected_val}()")
    print(f"Output: {dut.data_out_0.value}")
    print(f"Guess: {res_ind}")
    print(f"=============================")

    assert res_ind == expected_val

