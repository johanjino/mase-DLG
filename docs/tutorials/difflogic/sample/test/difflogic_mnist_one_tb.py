async def init(dut: HierarchyObject) -> None:
    # Start clk
    await cocotb.start(Clock(dut.clk, 3.2, units = "ns").start())

    dut.rst.value = 1

    await RisingEdge(dut.clk)
    await ClockCycles(dut.clk, 1)

    dut.rst.value = 0
    dut.data_out_0_ready.value = 1

def sw2hw(img):
    out = []
    for row in img:
        num = ''
        for i in range(len(row)-1,-1,-1):
            num += str(row[i])
        num = int(num, 2)
        out.append(num)
    return out

